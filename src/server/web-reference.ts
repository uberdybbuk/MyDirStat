/**
 * Shrink an ASMX web service proxy to
 * what a reader needs from it: the service's operations and the data types
 * they take and return. Visual Studio writes these as `Web References/<Name>/
 * Reference.cs`, and `wsdl.exe` as `<ServiceName>.cs` anywhere, so they are
 * found by content rather than by name.
 *
 * Visual Studio's generator writes, for every operation, a synchronous method,
 * a Begin/End pair, two Async overloads, an OnXOperationCompleted callback, a
 * SendOrPostCallback field, an event, a delegate and an EventArgs class. Every
 * data type carries a backing field plus a get/set body per property and five
 * or six attributes. The operation list is a small fraction of that.
 *
 * The result is deliberately not compilable: the client class becomes an
 * interface of the same name holding only the synchronous operations, and data
 * classes keep only their public properties as auto-properties. "Update Web
 * Reference" in Visual Studio brings the full proxy back.
 *
 * The parser is not a general C# parser. It reads the generator's output, which
 * is very regular: declarations separated by `;` or a braced body, attributes
 * in brackets before them. It is string and comment aware, so a `{` inside a
 * SOAP action URL or a doc comment cannot unbalance it. Anything it does not
 * recognise is dropped, never guessed at, and a file without a proxy class in
 * it is left alone (`minimizeReference` returns null).
 */

const OPERATION_ATTRIBUTE = /\b(?:SoapDocumentMethod|SoapRpcMethod|HttpMethod)(?:Attribute)?\b/;
const XML_IGNORE = /\bXmlIgnore(?:Attribute)?\b/;
const PROXY_BASE = /\b(?:SoapHttpClientProtocol|HttpGetClientProtocol|HttpPostClientProtocol|HttpSimpleClientProtocol)\b/;
const EVENT_ARGS_BASE = /\bAsyncCompletedEventArgs\b/;
/** The header Visual Studio and wsdl.exe put at the top of what they generate. */
const GENERATED_HEADER = /<auto-generated>|auto-generated by|generated by a tool/i;
/** How far into a file the generated header and the proxy class are looked for. */
export const SNIFF_BYTES = 16 * 1024;

/**
 * Cheap test on the start of a file: generated code with an ASMX client class.
 *
 * Both halves matter. A hand-written `partial class` that extends a proxy has
 * the same base class but no generated header, and minimizing it would throw
 * away code nobody can regenerate.
 */
export function looksLikeProxy(head: string): boolean {
    return GENERATED_HEADER.test(head.slice(0, 4096)) && PROXY_BASE.test(head);
}

const TYPE_DECL =
    /^((?:(?:public|internal|private|protected|partial|sealed|abstract|static|new|unsafe)\s+)*)(class|struct|interface|enum)\s+([A-Za-z_]\w*(?:\s*<[^>]*>)?)\s*(?::\s*(.+?))?\s*(?:where\s.+)?$/;
const MODIFIERS =
    /^(?:(?:public|private|protected|internal|static|virtual|override|new|sealed|abstract|extern|unsafe|readonly|partial)\s+)*/;

interface Item {
    attrs: string[];
    /** Declaration text before the body or `;`, whitespace collapsed. */
    header: string;
    /** Text between the braces, or null for a `;`-terminated declaration. */
    body: string | null;
}

/** Index just past the comment or literal starting at `i`, or `i` if none does. */
function skipLiteral(src: string, i: number): number {
    const c = src[i];
    const n = src[i + 1];
    if (c === '/' && n === '/') {
        const end = src.indexOf('\n', i);
        return end < 0 ? src.length : end;
    }
    if (c === '/' && n === '*') {
        const end = src.indexOf('*/', i + 2);
        return end < 0 ? src.length : end + 2;
    }
    if (c === '@' && n === '"') {
        let j = i + 2;
        while (j < src.length) {
            if (src[j] === '"') {
                if (src[j + 1] === '"') {
                    j += 2;
                    continue;
                }
                return j + 1;
            }
            j++;
        }
        return src.length;
    }
    if (c === '"' || c === "'") {
        let j = i + 1;
        while (j < src.length && src[j] !== c && src[j] !== '\n') {
            if (src[j] === '\\') j++;
            j++;
        }
        return Math.min(j + 1, src.length);
    }
    return i;
}

const OPEN = '([{';
const CLOSE = ')]}';

/** Index of the bracket closing the one at `i`. Throws on unbalanced input. */
function matchClose(src: string, i: number): number {
    const stack: string[] = [];
    let j = i;
    while (j < src.length) {
        const skipped = skipLiteral(src, j);
        if (skipped !== j) {
            j = skipped;
            continue;
        }
        const c = src[j];
        if (OPEN.includes(c)) {
            stack.push(CLOSE[OPEN.indexOf(c)]);
        } else if (CLOSE.includes(c)) {
            if (stack.pop() !== c) throw new Error(`Unbalanced '${c}' at ${j}`);
            if (stack.length === 0) return j;
        }
        j++;
    }
    throw new Error(`Unclosed '${src[i]}' at ${i}`);
}

/** Whitespace, comments and preprocessor lines, from `i` on. */
function skipTrivia(src: string, i: number): number {
    let j = i;
    for (;;) {
        while (j < src.length && /\s/.test(src[j])) j++;
        if (src[j] === '/' && (src[j + 1] === '/' || src[j + 1] === '*')) {
            j = skipLiteral(src, j);
            continue;
        }
        if (src[j] === '#') {
            const end = src.indexOf('\n', j);
            j = end < 0 ? src.length : end;
            continue;
        }
        return j;
    }
}

/** The declarations in one scope, in order. */
function readItems(src: string): Item[] {
    const items: Item[] = [];
    let pos = 0;
    for (;;) {
        pos = skipTrivia(src, pos);
        if (pos >= src.length) return items;

        const attrs: string[] = [];
        while (src[pos] === '[') {
            const end = matchClose(src, pos);
            attrs.push(src.slice(pos, end + 1));
            pos = skipTrivia(src, end + 1);
        }
        if (pos >= src.length) return items;

        let j = pos;
        let item: Item | null = null;
        while (j < src.length) {
            const skipped = skipLiteral(src, j);
            if (skipped !== j) {
                j = skipped;
                continue;
            }
            const c = src[j];
            if (c === '(' || c === '[') {
                j = matchClose(src, j) + 1;
                continue;
            }
            if (c === '{') {
                const end = matchClose(src, j);
                item = { attrs, header: collapse(src.slice(pos, j)), body: src.slice(j + 1, end) };
                pos = end + 1;
                break;
            }
            if (c === ';') {
                item = { attrs, header: collapse(src.slice(pos, j)), body: null };
                pos = j + 1;
                break;
            }
            if (c === '}') throw new Error(`Unexpected '}' at ${j}`);
            j++;
        }
        if (!item) {
            // Trailing text with no terminator: nothing the generator writes.
            return items;
        }
        if (item.header !== '' || item.body !== null) items.push(item);
    }
}

/** Collapse whitespace and drop comments inside a declaration's text. */
function collapse(text: string): string {
    let out = '';
    let i = 0;
    while (i < text.length) {
        if (text[i] === '/' && (text[i + 1] === '/' || text[i + 1] === '*')) {
            i = skipLiteral(text, i);
            out += ' ';
            continue;
        }
        const skipped = skipLiteral(text, i);
        if (skipped !== i) {
            out += text.slice(i, skipped);
            i = skipped;
            continue;
        }
        out += text[i];
        i++;
    }
    return out.replace(/\s+/g, ' ').trim();
}

/**
 * Drop attribute sections from a parameter list, keeping array ranks: `[]` and
 * `[,]` are types, anything with a name in it is an attribute.
 */
function stripAttributes(text: string): string {
    let out = '';
    let i = 0;
    while (i < text.length) {
        const skipped = skipLiteral(text, i);
        if (skipped !== i) {
            out += text.slice(i, skipped);
            i = skipped;
            continue;
        }
        if (text[i] === '[') {
            const end = matchClose(text, i);
            const inner = text.slice(i + 1, end);
            if (/^[\s,]*$/.test(inner)) out += text.slice(i, end + 1);
            i = end + 1;
            continue;
        }
        out += text[i];
        i++;
    }
    return out.replace(/\s+/g, ' ').replace(/\(\s+/g, '(').replace(/\s+\)/g, ')').trim();
}

function modifiersOf(header: string): string {
    return MODIFIERS.exec(header)?.[0] ?? '';
}

function isPublic(header: string): boolean {
    return /\bpublic\b/.test(modifiersOf(header));
}

/**
 * `public Result Name(string a, [Attr] int b)` -> `Result Name(string a, int b);`
 * Null for a constructor or anything that is not a method.
 */
function operationSignature(header: string): string | null {
    const open = header.indexOf('(');
    if (open < 0 || !header.endsWith(')')) return null;
    const head = header.slice(modifiersOf(header).length, open).trim();
    const space = head.lastIndexOf(' ');
    if (space < 0) return null; // constructor: no return type
    const returnType = head.slice(0, space).trim();
    const name = head.slice(space + 1);
    const params = stripAttributes(header.slice(open + 1, header.length - 1));
    return `${returnType} ${name}(${params});`;
}

/** `public Foo Bar` with a get/set body -> `public Foo Bar { get; set; }` */
function autoProperty(header: string, body: string): string {
    const plain = collapse(body);
    const accessors: string[] = [];
    if (/(^|[\s;}])get\s*[{;]/.test(plain)) accessors.push('get;');
    if (/(^|[\s;}])set\s*[{;]/.test(plain)) accessors.push('set;');
    const decl = header.slice(modifiersOf(header).length).trim();
    return `public ${decl} { ${accessors.join(' ')} }`;
}

function baseList(bases: string | undefined): string {
    if (!bases) return '';
    const kept = splitTopLevel(bases, ',')
        .map((b) => b.trim())
        .filter((b) => b !== '' && !/\bINotifyPropertyChanged\b/.test(b));
    return kept.length > 0 ? ` : ${kept.join(', ')}` : '';
}

/** Split on `sep` outside of brackets and generic angle brackets. */
function splitTopLevel(text: string, sep: string): string[] {
    const parts: string[] = [];
    let depth = 0;
    let start = 0;
    for (let i = 0; i < text.length; i++) {
        const skipped = skipLiteral(text, i);
        if (skipped !== i) {
            i = skipped - 1;
            continue;
        }
        const c = text[i];
        if ('([{<'.includes(c)) depth++;
        else if (')]}>'.includes(c)) depth--;
        else if (c === sep && depth === 0) {
            parts.push(text.slice(start, i));
            start = i + 1;
        }
    }
    parts.push(text.slice(start));
    return parts;
}

class Writer {
    readonly lines: string[] = [];
    line(depth: number, text: string): void {
        this.lines.push(text === '' ? '' : '    '.repeat(depth) + text);
    }
}

interface Context {
    out: Writer;
    proxies: number;
    operations: number;
}

function emitScope(items: Item[], depth: number, ctx: Context): void {
    const usings = new Set<string>();
    for (const item of items) {
        if (item.body === null && /^using\s+[^(]/.test(item.header)) {
            if (!usings.has(item.header)) {
                usings.add(item.header);
                ctx.out.line(depth, `${item.header};`);
            }
        }
    }
    if (usings.size > 0) ctx.out.line(0, '');

    for (const item of items) {
        if (item.body === null) continue; // usings above; delegates and the rest dropped
        const ns = /^namespace\s+(.+)$/.exec(item.header);
        if (ns) {
            ctx.out.line(depth, `namespace ${ns[1]} {`);
            emitScope(readItems(item.body), depth + 1, ctx);
            ctx.out.line(depth, '}');
            ctx.out.line(0, '');
            continue;
        }
        emitType(item, depth, ctx);
    }
    trimTrailingBlank(ctx.out);
}

function trimTrailingBlank(out: Writer): void {
    while (out.lines.length > 0 && out.lines[out.lines.length - 1] === '') out.lines.pop();
}

function emitType(item: Item, depth: number, ctx: Context): void {
    const decl = TYPE_DECL.exec(item.header);
    if (!decl || item.body === null) return;
    const [, , kind, name, bases] = decl;

    if (kind === 'enum') {
        emitEnum(name, item.body, depth, ctx);
        return;
    }
    if (bases && EVENT_ARGS_BASE.test(bases)) return; // XCompletedEventArgs

    if (kind === 'class' && bases && PROXY_BASE.test(bases)) {
        ctx.proxies += 1;
        ctx.out.line(depth, `public interface ${name} {`);
        for (const member of readItems(item.body)) {
            if (member.body === null && !member.header.includes('(')) continue;
            if (!member.attrs.some((a) => OPERATION_ATTRIBUTE.test(a))) continue;
            const signature = operationSignature(member.header);
            if (!signature) continue;
            ctx.operations += 1;
            ctx.out.line(depth + 1, signature);
        }
        ctx.out.line(depth, '}');
        ctx.out.line(0, '');
        return;
    }

    // A data type: public properties and fields only.
    const members: string[] = [];
    const nested: Item[] = [];
    for (const member of readItems(item.body)) {
        if (TYPE_DECL.test(member.header)) {
            nested.push(member);
            continue;
        }
        if (!isPublic(member.header) || /\bevent\b/.test(member.header)) continue;
        if (member.attrs.some((a) => XML_IGNORE.test(a))) continue;
        if (member.header.includes('(')) continue; // methods, constructors
        if (member.body !== null) members.push(autoProperty(member.header, member.body));
        else members.push(`${stripAttributes(member.header)};`);
    }

    const keyword = kind === 'struct' ? 'struct' : kind === 'interface' ? 'interface' : 'class';
    const head = `public ${keyword} ${name}${baseList(bases)}`;
    if (members.length === 0 && nested.length === 0) {
        ctx.out.line(depth, `${head} { }`);
    } else {
        ctx.out.line(depth, `${head} {`);
        for (const m of members) ctx.out.line(depth + 1, m);
        for (const n of nested) emitType(n, depth + 1, ctx);
        trimTrailingBlank(ctx.out);
        ctx.out.line(depth, '}');
    }
    ctx.out.line(0, '');
}

function emitEnum(name: string, body: string, depth: number, ctx: Context): void {
    const values = splitTopLevel(body, ',')
        .map((part) => stripAttributes(collapse(part)))
        .filter((v) => v !== '');
    ctx.out.line(depth, `public enum ${name} {`);
    for (const v of values) ctx.out.line(depth + 1, `${v},`);
    ctx.out.line(depth, '}');
    ctx.out.line(0, '');
}

export interface MinimizedReference {
    text: string;
    operations: number;
}

/**
 * The reduced proxy, or null when the text holds no ASMX proxy class (already
 * minimized, a WCF service reference, or not generated code at all). Throws when
 * the text cannot be read as C#.
 */
export function minimizeReference(source: string, originalBytes: number): MinimizedReference | null {
    if (!GENERATED_HEADER.test(source.slice(0, 4096))) return null;
    const ctx: Context = { out: new Writer(), proxies: 0, operations: 0 };
    ctx.out.line(0, '//------------------------------------------------------------------------------');
    ctx.out.line(0, `// Minimized by MyDirStat from the generated web reference proxy (${originalBytes} bytes).`);
    ctx.out.line(0, '// Only the synchronous operations and the data types are kept. This file does');
    ctx.out.line(0, '// not compile. Use "Update Web Reference" in Visual Studio to regenerate it.');
    ctx.out.line(0, '//------------------------------------------------------------------------------');
    ctx.out.line(0, '');
    emitScope(readItems(source), 0, ctx);
    if (ctx.proxies === 0) return null;
    return { text: ctx.out.lines.join('\n') + '\n', operations: ctx.operations };
}

/**
 * File bytes in, file bytes out, keeping the original's BOM and line endings
 * so a diff in source control shows content changes only.
 */
export function minimizeReferenceFile(bytes: Buffer): Buffer | null {
    let text: string;
    let bom: Buffer = Buffer.alloc(0);
    let encoding: BufferEncoding = 'utf8';
    if (bytes[0] === 0xef && bytes[1] === 0xbb && bytes[2] === 0xbf) {
        bom = bytes.subarray(0, 3);
        text = bytes.subarray(3).toString('utf8');
    } else if (bytes[0] === 0xff && bytes[1] === 0xfe) {
        bom = bytes.subarray(0, 2);
        encoding = 'utf16le';
        text = bytes.subarray(2).toString('utf16le');
    } else {
        text = bytes.toString('utf8');
    }

    const result = minimizeReference(text, bytes.length);
    if (!result) return null;
    const out = text.includes('\r\n') ? result.text.replace(/\n/g, '\r\n') : result.text;
    return Buffer.concat([bom, Buffer.from(out, encoding)]);
}
